import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const read = path => readFile(resolve(root, path), 'utf8');
const common = await read('prompts/interviewer.md');
const rubric = await read('prompts/rubric.md');
for (const [track, name, description] of [
  ['ai-algorithm', 'AI 算法面试教练', '机器学习、LLM 算法、推导、代码静态审阅与实验复盘。'],
  ['agent-engineer', 'Agent 岗位面试教练', 'RAG、工具调用、Agent 系统设计、评估与项目追问。'],
]) {
  const prompt = [common.trim(), (await read(`prompts/${track}.md`)).trim(), rubric.trim()].join('\n\n');
  const files = {
    'preset.yml': `name: ${name}\ndescription: ${description}\norder: 20\n`,
    'agent.cordis.yml': '# Generated by scripts/build-presets.mjs; edit prompts/*.md.\n'
      + '# Persona row derived from the shipped standard preset (DSH 0.2.0-rc.2).\n'
      + '# Agent plane only. No additional tools or host providers.\n'
      + "- id: persona\n  name: '@deepseek-ai/dsh-persona'\n  config:\n    text: |-\n"
      + prompt.split('\n').map(line => `      ${line}`).join('\n') + '\n',
  };
  const dir = resolve(root, 'presets', `interview-${track}`);
  if (!check) await mkdir(dir, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    const target = resolve(dir, name);
    if (check) {
      if (await readFile(target, 'utf8') !== text) throw new Error(`Generated preset drift: ${track}/${name}`);
    } else await writeFile(target, text);
  }
  console.log(`${check ? 'Checked' : 'Built'} interview-${track}`);
}
